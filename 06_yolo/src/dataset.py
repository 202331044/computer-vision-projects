import cv2
import torch
import numpy as np
import os
from torch.utils.data import Dataset
from torchvision.datasets import VOCDetection

class VOCDataset(Dataset):
    def __init__(
        self, 
        image_set, 
        target_width, 
        target_height, 
        grid_size,
        transform = None,
    ):

        self.grid_size = grid_size
        self.target_width = target_width
        self.target_height = target_height
        self.transform = transform

        self.dataset = VOCDetection(
            root = './data',
            year = '2007',
            image_set = image_set,
            download = True,
        )

        self.VOC_CLASSES = [
            "aeroplane",
            "bicycle",
            "bird",
            "boat",
            "bottle",
            "bus",
            "car",
            "cat",
            "chair",
            "cow",
            "diningtable",
            "dog",
            "horse",
            "motorbike",
            "person",
            "pottedplant",
            "sheep",
            "sofa",
            "train",
            "tvmonitor",
        ]

        """
        Dataset attributes:
            dataset: PASCAL VOC 2007 dataset split specified by image_set.
            class_id_dict: Mapping from class names to integer class indices.
            targets: List of object annotations generated by _make_targets().
        """
        
        self.class_id_dict = { name: idx for idx, name in enumerate(self.VOC_CLASSES)}
        
        self.targets = self._make_targets()

    def _make_targets(self):
        
        """
        Convert object annotations into bounding box targets for all images.

            Returns:
                list: A list of target lists, one for each image.

                    Each object is represented as:
                    [x_center, y_center, width, height, class_idx]

                    - x_center, y_center: Center coordinates of the bounding box in pixels.
                    - width, height: Bounding box dimensions in pixels.
                    - class_idx: Integer index of the object class (0–19).
        """

        all_targets = []

        for _, annotations in self.dataset:
            image_targets = []
            objects = annotations['annotation']['object']
            
            for obj in objects:
                bbox = obj['bndbox']
                
                xmin = float(bbox['xmin'])
                ymin = float(bbox['ymin'])
                xmax = float(bbox['xmax'])
                ymax = float(bbox['ymax'])

                width = xmax - xmin
                height = ymax - ymin
                x_center = xmin + (width / 2)
                y_center = ymin + (height / 2)

                class_idx = self.class_id_dict[obj['name']]

                image_targets.append([x_center, y_center, width, height, class_idx])

            all_targets.append(image_targets)

        return all_targets

    def __len__(self):
        return len(self.dataset)

    def __getitem__(self, idx):
        """
        Load and preprocess an image and its bounding box annotations.

        The image is resized while preserving its aspect ratio, then padded
        to the target dimensions. Bounding box coordinates are transformed
        accordingly and assigned to grid cells.

        Each bounding box is represented by:
            [x_cell_offset, y_cell_offset, bbox_w_ratio, bbox_h_ratio,
            class_id, objectness]

        Returns:
            padded_img (Tensor): Resized and padded image.

            target_bbox (Tensor): Tensor of shape [grid_size, grid_size, 6],
                containing the target values for each grid cell.

                - x_cell_offset, y_cell_offset: Bounding box center coordinates
                relative to the assigned grid cell, normalized to [0, 1).
                - bbox_w_ratio, bbox_h_ratio: Bounding box width and height
                normalized by the target image dimensions.
                - class_id: Integer index of the object class.
                - objectness: 1 if an object is assigned to the cell,
                otherwise 0.

            filename (str): Name of the image file.
        """
        
        img, _ = self.dataset[idx]
        targets = self.targets[idx]
        img = np.array(img)

        # Resize the image while preserving its aspect ratio.
        img_h, img_w = img.shape[:2]
        scale = min(
            self.target_width / img_w, 
            self.target_height / img_h
        )

        resized_w = int(img_w * scale)
        resized_h = int(img_h * scale)
        
        resized_img = cv2.resize(img, (resized_w, resized_h))

        # Pad the image to the target dimensions.
        pad_w = self.target_width - resized_w
        pad_h = self.target_height - resized_h

        left, top = pad_w // 2, pad_h // 2
        right, bottom = pad_w - left, pad_h - top

        padded_img = cv2.copyMakeBorder(
            resized_img,
            top,
            bottom,
            left,
            right,
            cv2.BORDER_CONSTANT,
            value = (114, 114, 114),
        )

        if self.transform is not None:
            padded_img = self.transform(padded_img)

        # Initialize the target tensor.
        target_bbox = torch.zeros(
            self.grid_size,
            self.grid_size,
            6,
            dtype = torch.float32
        )

        x_scale = resized_w / img_w
        y_scale = resized_h / img_h

        for x, y, w, h, class_idx in targets:
            # Scale and normalize bounding box coordinates.
            x = (x * x_scale + left) / self.target_width
            y = (y * y_scale + top) / self.target_height

            w = (w * x_scale) / self.target_width
            h = (h * y_scale) / self.target_height

            # Assign the bounding box to a grid cell.
            grid_x = x * self.grid_size
            grid_y = y * self.grid_size

            col = min(int(grid_x), self.grid_size - 1)
            row = min(int(grid_y), self.grid_size - 1)
            
            # Keep only the first object assigned to each grid cell.
            if target_bbox[row, col, 5] == 1:
                continue

            target_bbox[row, col] = torch.tensor([
                grid_x - col, 
                grid_y - row, 
                w, 
                h, 
                class_idx, 
                1],
                dtype=torch.float32
            )
        
        filename = os.path.basename(self.dataset.images[idx])

        return padded_img, target_bbox, filename